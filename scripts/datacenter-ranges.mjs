// Builds lib/datacenter-ranges.json: the IP ranges announced by big cloud and
// hosting networks, so a visit from a server (a bot) can be told apart from a
// person at home or on a phone. Uses RIPEstat's public routing data.
//
//   node scripts/datacenter-ranges.mjs
//
// Re-run every few months; networks change slowly.
//
// Not listed on purpose: Akamai, Cloudflare and Fastly. iCloud Private Relay
// and other privacy proxies exit through them, so real people come from there.

import { writeFileSync } from 'node:fs';

const PROVIDERS = {
  'Amazon AWS': [16509, 14618, 8987],
  'Google': [15169, 396982, 19527, 36040, 43515],
  'Microsoft Azure': [8075, 8068, 8069, 12076],
  'Meta': [32934, 63293, 54115],
  'OVH': [16276, 35540],
  'Hetzner': [24940, 213230, 212317],
  'DigitalOcean': [14061],
  'Oracle Cloud': [31898],
  'Linode': [63949],
  'Vultr': [20473],
  'Alibaba Cloud': [45102, 37963],
  'Tencent Cloud': [132203, 45090],
  'Scaleway': [12876],
  'Contabo': [51167],
  'Leaseweb': [60781, 16265, 28753],
  'IONOS': [8560],
};

const v4ToInt = (ip) => ip.split('.').reduce((n, p) => n * 256 + Number(p), 0);

function v6Top64(ip) {
  const [head, tail = ''] = ip.split('::');
  const h = head ? head.split(':') : [];
  const t = tail ? tail.split(':') : [];
  const groups = ip.includes('::') ? [...h, ...Array(8 - h.length - t.length).fill('0'), ...t] : h;
  return groups.slice(0, 4).reduce((n, g) => (n << 16n) | BigInt(parseInt(g || '0', 16)), 0n);
}

const v4 = [];
const v6 = [];
const names = Object.keys(PROVIDERS);

for (const [pi, name] of names.entries()) {
  for (const asn of PROVIDERS[name]) {
    const url = `https://stat.ripe.net/data/announced-prefixes/data.json?resource=AS${asn}&sourceapp=fabjanelezi-dev`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`AS${asn}: HTTP ${res.status}`);
    const { data } = await res.json();
    let n = 0;
    for (const { prefix } of data.prefixes) {
      const [addr, bits] = prefix.split('/');
      const len = Number(bits);
      if (addr.includes(':')) {
        if (len > 64) continue; // finer than /64 never matters here
        const start = v6Top64(addr);
        const size = 1n << BigInt(64 - len);
        v6.push([start, start + size - 1n, pi]);
      } else {
        const start = v4ToInt(addr);
        v4.push([start, start + 2 ** (32 - len) - 1, pi]);
      }
      n++;
    }
    console.log(`${name.padEnd(16)} AS${asn}: ${n} prefixes`);
  }
}

// Sort and merge overlapping or touching ranges of the same provider.
function merge(list, one) {
  list.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  const out = [];
  for (const r of list) {
    const last = out[out.length - 1];
    if (last && r[0] <= last[1] + one) {
      if (r[1] > last[1]) {
        if (r[2] === last[2]) last[1] = r[1];
        else out.push([last[1] + one, r[1], r[2]]); // overlap between providers: keep the first
      }
      continue;
    }
    out.push([...r]);
  }
  return out;
}

const m4 = merge(v4, 1);
const m6 = merge(v6, 1n);

const hex = (b) => b.toString(16).padStart(16, '0');
const out = {
  note: 'Generated by scripts/datacenter-ranges.mjs from RIPEstat. Do not edit by hand.',
  updated: new Date().toISOString().slice(0, 10),
  providers: names,
  // Flat lists: start, end, provider index, ...
  v4: m4.flat(),
  v6: m6.flatMap(([s, e, p]) => [hex(s), hex(e), p]),
};
writeFileSync(new URL('../lib/datacenter-ranges.json', import.meta.url), JSON.stringify(out));
console.log(`\n${m4.length} IPv4 ranges, ${m6.length} IPv6 ranges written.`);
